-- 34	Identify customers who returned after long gaps between orders.
WITH orderGaps AS(
	SELECT custId,orderDate,
    -- GET THE DATE OF THE CUSTOMER'S NEXT ORDERS
    LEAD(orderDate) OVER (PARTITION BY custId ORDER BY orderDate) AS nextOrderDate,
    -- CALCULATE THE DAYS UNTIL THE NEXT ORDER
    DATEDIFF(LEAD(orderDate) OVER(PARTITION BY custId ORDER BY orderDate),orderDate) AS daysBetweenOrders
FROM orders)
SELECT DISTINCT c.custId,c.custName,c.city
FROM orderGaps og JOIN customers c
ON og.custId = c.custId
WHERE og.daysBetweenOrders > 180;          -- Defines a "long gap" as more than 180 days (6 months)

-- OR

WITH OrderGaps AS (
    SELECT 
        custId,
        orderDate,
        LAG(orderDate) OVER (PARTITION BY custId ORDER BY orderDate) AS previousOrderDate
    FROM orders
)
SELECT 
    custId,
    orderDate AS currentOrderDate,
    previousOrderDate,
    DATEDIFF(orderDate, previousOrderDate) AS daysBetweenOrders
FROM OrderGaps
WHERE previousOrderDate IS NOT NULL 
  AND DATEDIFF(orderDate, previousOrderDate) > 180 -- Change 180 to whatever number of days you consider a "long gap"
ORDER BY daysBetweenOrders DESC;


