-- 29	Show top 3 customers in each city using RANK() window function.
WITH rankedCustomers AS(
	SELECT c.city,c.custName,c.custId,
    SUM(od.quantity * od.price * (1 - IFNULL(od.discount,0))) AS totalSpent,
    RANK() OVER (PARTITION BY c.city ORDER BY SUM(od.quantity * od.price * (1 - IFNULL(DISCOUNT,0)))DESC) AS customerRank
    FROM customers c JOIN orders o
    ON c.custId= o.custId
    JOIN orderdetails od
    ON o.orderId = od.orderId
    GROUP BY c.custId,c.custName,c.city
)
SELECT city,custId,custName,totalSpent
FROM rankedCustomers
WHERE customerRank <=3
ORDER BY city,customerRank;

